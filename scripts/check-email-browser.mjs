import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { createApp } from '../server.mjs';
import { CaseStore } from '../src/store.mjs';
import { EmailFixtureAI } from '../tests/helpers/email-fixture.mjs';
import { emailCases, emailThread } from '../evals/email-cases.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.REPLYTRACK_PLAYWRIGHT_MODULE || 'playwright');
const dir = '.artifacts/email-browser'; await mkdir(dir, { recursive: true });
const ai = new EmailFixtureAI(), app = createApp({ store: new CaseStore(':memory:'), ai });
await new Promise(r => app.server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${app.server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.REPLYTRACK_CHROMIUM, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
page.setDefaultTimeout(30000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
const idle = () => page.waitForFunction(() => !document.querySelector('.busy-bar'));
try {
  await page.goto(base);
  await page.locator('[data-action=new]').first().click();
  await page.locator('[name=channel]').selectOption('email');
  await page.locator('#import-form [name=title]').fill('이메일 계정 복구');
  await page.locator('[name=myAddress]').fill('me@example.test');
  await page.locator('#import-form [name=text]').fill(emailThread(emailCases[0]));
  await page.locator('#import-form button[type=submit]').click(); await idle();
  await page.locator('#privacy-form button[type=submit]').click(); await idle();
  assert.equal(await page.locator('.review-row').count(), 2);
  await page.locator('#review-form button[type=submit]').click(); await idle();
  await page.locator('[data-action=explain-email]').click(); await idle();
  assert.match(await page.locator('.email-explanation').innerText(), /비밀번호나 인증 코드/);
  await page.locator('[data-action=tab][data-value=drafts]').click();
  assert.equal(await page.locator('#reply-language').inputValue(), 'en');
  await page.locator('#reply-language').selectOption('ko');
  await page.locator('[data-action=tab][data-value=questions]').click();
  await page.locator('[data-action=tab][data-value=drafts]').click();
  assert.equal(await page.locator('#reply-language').inputValue(), 'ko');
  await page.locator('#reply-language').selectOption('en');
  await page.locator('[data-action=generate-draft][data-kind=followup]').click(); await idle();
  assert.match(await page.locator('#draft-followup').inputValue(), /How long/);
  await page.screenshot({ path: `${dir}/desktop.png`, fullPage: true });
  await page.locator('[data-action=append]').first().click();
  await page.locator('#import-form [name=text]').fill(emailThread(emailCases[0], true));
  await page.locator('#import-form button[type=submit]').click(); await idle();
  await page.locator('#privacy-form button[type=submit]').click(); await idle();
  assert.equal(await page.locator('.review-row').count(), 1);
  await page.locator('#review-form button[type=submit]').click(); await idle();
  await page.locator('#analysis-changes').waitFor();
  assert.match(await page.locator('.email-explanation').innerText(), /이전 답변 기준/);
  await page.locator('[data-action=explain-email]').click(); await idle();
  assert.equal(await page.locator('.email-explanation-item').count(), 2);
  assert.match(await page.locator('.email-explanation').innerText(), /아직 복구되지/);
  await page.reload(); await idle();
  await page.locator('.email-explanation-item').first().waitFor();
  assert.equal(await page.locator('.email-explanation-item').count(), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${dir}/mobile.png`, fullPage: true });

  // Screenshot fixture rendered locally; actual Tesseract OCR, deterministic AI transport.
  const imagePage = await browser.newPage({ viewport: { width: 1100, height: 720 } });
  await imagePage.setContent(`<html><body style="font:22px Arial;padding:24px;line-height:1.8"><h1>Account recovery</h1><p>From: me@example.test</p><p>${emailCases[0].customer}</p><hr><p>From: support@example.test</p><p>${emailCases[0].agent}</p></body></html>`);
  await imagePage.screenshot({ path: `${dir}/email-capture.png` }); await imagePage.close();
  await page.locator('[data-action=new]').first().click();
  await page.locator('[name=channel]').selectOption('email');
  await page.locator('#import-form [name=title]').fill('캡처 이메일');
  await page.locator('[name=image]').setInputFiles(`${dir}/email-capture.png`);
  await page.locator('#import-form button[type=submit]').click(); await idle();
  const ocr = await page.locator('#privacy-form textarea').inputValue();
  assert.match(ocr, /transaction ID/);
  await page.locator('#privacy-form button[type=submit]').click(); await idle();
  assert.equal(await page.locator('.review-row').count(), 2);
  await page.locator('#review-form button[type=submit]').click(); await idle();
  await page.locator('[data-action=explain-email]').click(); await idle();
  assert.equal(await page.locator('.email-explanation-item').count(), 1);
  assert(ai.calls.every(c => !c.image));
  assert.deepEqual(errors, []);
  await writeFile(`${dir}/result.json`, JSON.stringify({ passed: true, inputModes: ['text', 'real-local-ocr'], viewports: [1440, 390], calls: ai.calls.length, errors, ai: 'deterministic fixtures, not live AI' }, null, 2));
  console.log('Email browser flow passed: text, real OCR, Korean explanation, English draft, reply comparison, stale refresh, reload and mobile.');
} finally { await browser.close(); await new Promise(r => app.server.close(r)); app.store.close(); }
