// Browser acceptance with isolated in-memory records and explicitly fake AI responses.
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../server.mjs';
import { CaseStore } from '../src/store.mjs';
import { createRefundDemo, demoActions } from '../src/demo.mjs';
import { actionChecks } from '../src/feature-review.mjs';
const require=createRequire(import.meta.url);
const { chromium }=require(process.env.REPLYTRACK_PLAYWRIGHT_MODULE || 'playwright');
const out=resolve('.artifacts/next-actions'); await mkdir(out,{recursive:true});
let hold=false, release, reviewValid=true, called=0;
const ai={configured:true,model:'browser-fixture',structured:async p=>{
  if(p.name==='replytrack_connection') return {data:{ok:true}};
  if(p.name==='replytrack_actions_review') return {data:{checks:Object.fromEntries(Object.keys(actionChecks).map(key=>[key,reviewValid])),valid:reviewValid,feedback:reviewValid?'':'검증 실패 시연'}};
  if(p.name==='replytrack_actions') {
    called++;
    if(hold) await new Promise(r=>{release=r;});
    const c=app.store.get(live.id);
    return {data:demoActions(c),model:'browser-fixture'};
  }
  throw new Error(`Unexpected fixture request: ${p.name}`);
}};
const app=createApp({store:new CaseStore(':memory:'),ai});
const record=createRefundDemo(); record.mode='live'; record.title='환불 할 일 오류·취소 검증';
record.drafts.followup={body:'저장된 환불 문의 초안',sourceMessageIds:record.messages.map(m=>m.id)};
const live=app.store.create(record);
await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
const origin=`http://127.0.0.1:${app.server.address().port}`;
let browser;
const checks=[],errors=[];
try {
  browser=await chromium.launch({executablePath:process.env.REPLYTRACK_CHROMIUM || undefined,headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  page.on('pageerror',e=>errors.push(e.message)); page.setDefaultTimeout(12000);
  const idle=()=>page.waitForFunction(()=>!document.querySelector('.busy-bar'));
  await page.goto(origin);
  await page.locator('.sidebar [data-action="demo"]').click(); await idle();
  await page.getByRole('heading',{name:'지금 내가 할 일',exact:true}).waitFor();
  assert.match(await page.locator('#next-actions').innerText(),/불량 사진 보내기/);
  assert.match(await page.locator('#next-actions').innerText(),/AI 제안 · 업체 요청 아님/);
  const demoId=new URL(page.url()).searchParams.get('case');
  await page.locator('#next-actions .action-source').first().click();
  await page.locator('.message.highlight').waitFor();
  assert.match(await page.locator('.message.highlight').innerText(),/불량 사진/);
  await page.locator('[data-action="complete-action"]').first().click();
  await page.locator('[data-action="action-complete-yes"]').click(); await idle();
  assert(app.store.get(demoId).nextActions.items[0].completedAt);
  assert.equal(app.store.get(demoId).promises[0].confirmedAt,null);
  await page.reload(); await page.locator('#next-actions').waitFor();
  await page.locator('.action-history summary').click();
  await page.getByRole('button',{name:'수행 표시 취소',exact:true}).click(); await idle();
  assert.equal(app.store.get(demoId).nextActions.items[0].completedAt,null);
  await page.locator('[data-action="action-followup"]').click();
  assert.equal(await page.locator('[name="draft-question"]:checked').count(),1);
  assert.match(await page.locator('[name="draft-question"]:checked').locator('..').innerText(),/배송비/);
  await page.locator('[data-action="tab"][data-value="questions"]').click();
  checks.push('Source navigation, completion/reload/undo, promise isolation, specific follow-up selection');
  await page.locator('#next-actions').scrollIntoViewIfNeeded();
  await page.screenshot({path:resolve(out,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-action="mobile"][data-value="analysis"]').click();
  await page.locator('#next-actions').scrollIntoViewIfNeeded();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('[data-action="read-actions"]').focus();
  assert.equal(await page.locator('[data-action="read-actions"]').evaluate(e=>getComputedStyle(e).outlineWidth),'3px');
  await page.screenshot({path:resolve(out,'mobile.png'),fullPage:true});
  checks.push('390px layout, keyboard focus, desktop and mobile screenshots');
  await page.locator('[data-action="demo-next"]').click(); await idle();
  assert.equal(app.store.get(demoId).nextActions.items[0].state,'reported_done');
  await page.locator('[data-action="demo-next"]').click(); await idle();
  assert.equal(app.store.get(demoId).promises.filter(p=>!p.confirmedAt).length,2);
  await page.locator('#next-actions [data-action="confirm-promise"]').last().click();
  await page.locator('[data-action="confirm-yes"]').click(); await idle();
  assert(app.store.get(demoId).promises[1].confirmedAt);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('[data-action="export"]').click();
  await (await downloadPromise).saveAs(resolve(out,'demo-export.md'));
  checks.push('Refund updates and actual completion remain separate; Markdown export works');

  await page.setViewportSize({width:1440,height:1050});
  await page.goto(`${origin}/?case=${live.id}`); await page.locator('#next-actions').waitFor();
  await page.locator('[data-action="tab"][data-value="drafts"]').click();
  await page.locator('#draft-followup').fill('아직 저장하지 않은 환불 문의');
  await page.locator('[data-action="tab"][data-value="questions"]').click();
  hold=true; const before=app.store.get(live.id);
  await page.locator('[data-action="read-actions"]').click();
  await page.locator('[data-progress]').filter({hasText:'업체가 요청한 할 일 읽는 중'}).waitFor();
  await page.locator('[data-action="cancel-operation"]').click(); await idle();
  hold=false; release();
  assert.deepEqual(app.store.get(live.id),before);
  await page.locator('[data-action="tab"][data-value="drafts"]').click();
  assert.equal(await page.locator('#draft-followup').inputValue(),'아직 저장하지 않은 환불 문의');
  await page.locator('[data-action="tab"][data-value="questions"]').click();
  reviewValid=false;
  await page.locator('[data-action="read-actions"]').click(); await idle();
  assert.match(await page.locator('.error-banner').innerText(),/저장하지 않았/);
  assert.deepEqual(app.store.get(live.id),before);
  reviewValid=true;
  await page.locator('[data-action="read-actions"]').click(); await idle();
  assert.equal(app.store.get(live.id).nextActions.reviewed,true);
  checks.push('Cancellable real web job protocol, review rejection, retry, saved and unsaved draft preservation');

  const updated=app.store.get(live.id);
  app.service.append(live.id,{version:updated.version,role:'agent',text:'사진 요청을 취소합니다.'});
  await page.goto(`${origin}/?case=${live.id}`); await page.locator('#next-actions').waitFor();
  assert.match(await page.locator('#next-actions').innerText(),/이전 기록/);
  assert(await page.locator('[data-action="complete-action"]').first().isDisabled());
  assert.equal(await page.locator('[data-action="action-followup"]').count(),0);
  checks.push('New messages flag old actions and prevent stale completion or follow-up suggestions');
  assert.equal(errors.length,0);
  await writeFile(resolve(out,'results.json'),JSON.stringify({checks,errors,called,ai:'Deterministic fixture; no paid API calls'},null,2));
  console.log(JSON.stringify({checks,errors,called},null,2));
} finally { release?.(); await browser?.close(); await new Promise(r=>app.server.close(r)); app.store.close(); }
