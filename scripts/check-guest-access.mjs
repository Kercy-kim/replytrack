// Real browser, real isolated PostgreSQL queries; deterministic AI, no paid API calls.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { createApp } from '../server.mjs';
import { testDatabase } from '../tests/helpers/postgres.mjs';
import { EmailFixtureAI } from '../tests/helpers/email-fixture.mjs';
import { emailCases, emailThread } from '../evals/email-cases.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.REPLYTRACK_PLAYWRIGHT_MODULE||'playwright');
const dir='.artifacts/guest-access';await mkdir(dir,{recursive:true});
const database=await testDatabase(),ai=new EmailFixtureAI();
const app=createApp({database,ai,hosting:{publicOrigin:null,password:''}});
await new Promise(r=>app.server.listen(0,'127.0.0.1',r));const base=`http://127.0.0.1:${app.server.address().port}`;
const browser=await chromium.launch({executablePath:process.env.REPLYTRACK_CHROMIUM,headless:true});
const first=await browser.newContext({viewport:{width:1440,height:1000}}),second=await browser.newContext({viewport:{width:390,height:844}});
const page=await first.newPage(),other=await second.newPage(),errors=[];
for(const p of [page,other])p.on('pageerror',e=>errors.push(e.message));
const idle=()=>page.waitForFunction(()=>!document.querySelector('.busy-bar'));
try{
  await page.goto(base);await page.locator('#guest-start').waitFor();
  await page.screenshot({path:`${dir}/entry-desktop.png`,fullPage:true});
  await other.goto(base);await other.locator('#guest-start').waitFor();
  assert(await other.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await other.screenshot({path:`${dir}/entry-mobile.png`,fullPage:true});
  // Empty required login fields must not interfere with anonymous entry.
  await page.locator('#guest-start').click();await page.locator('.account-button').waitFor();
  assert.equal(await page.locator('.account-button').innerText(),'비회원');
  await page.locator('[data-action=new]').first().click();
  await page.locator('[name=channel]').selectOption('email');
  await page.locator('#import-form [name=title]').fill('비회원 계정 복구 문의');
  await page.locator('#import-form [name=text]').fill(emailThread(emailCases[0]));
  await page.locator('#import-form button[type=submit]').click();await idle();
  await page.locator('#privacy-form button[type=submit]').click();await idle();
  await page.locator('#review-form button[type=submit]').click();await idle();
  await page.locator('[data-action=tab][data-value=drafts]').click();
  await page.locator('[data-action=generate-draft][data-kind=followup]').click();await idle();
  assert.match(await page.locator('#draft-followup').inputValue(),/How long/);
  await page.locator('[data-action=append]').first().click();
  await page.locator('#import-form [name=text]').fill(emailThread(emailCases[0],true));
  await page.locator('#import-form button[type=submit]').click();await idle();
  await page.locator('#privacy-form button[type=submit]').click();await idle();
  await page.locator('#review-form button[type=submit]').click();await idle();await page.locator('#analysis-changes').waitFor();
  const list=await (await page.request.get(base+'/api/cases')).json();assert.equal(list.length,1);
  await page.reload();await page.locator('.account-button').waitFor();
  assert.equal((await (await page.request.get(base+'/api/cases')).json())[0].id,list[0].id);
  await other.locator('#guest-start').click();await other.locator('.account-button').waitFor();
  assert.equal((await (await other.request.get(base+'/api/cases')).json()).length,0);
  assert.equal((await other.request.get(base+`/api/cases/${list[0].id}`)).status(),404);
  await page.locator('[data-action=account]').click();
  await page.locator('#modal[open]').waitFor();
  assert.match(await page.locator('#modal').innerText(),/비회원으로 이용 중/);
  await page.screenshot({path:`${dir}/guest-records.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:`${dir}/guest-account-mobile.png`,fullPage:true});
  await page.locator('[data-action=join]').click();await page.locator('#confirm-field').waitFor();
  await page.locator('[name=username]').fill('guest_browser');await page.locator('[name=password]').fill('Guest-browser-1234');await page.locator('[name=confirm]').fill('Guest-browser-1234');
  await page.locator('#auth-submit').click();await page.locator('.account-button').waitFor();
  assert.equal(await page.locator('.account-button').innerText(),'guest_browser');
  assert.equal((await (await page.request.get(base+'/api/cases')).json())[0].id,list[0].id);
  await page.locator('[data-action=account]').click();await page.locator('[data-action=logout]').click();await page.locator('#auth-submit').waitFor();
  // Start another guest, then link it to the existing account through the login UI.
  await page.locator('#guest-start').click();await page.locator('.account-button').waitFor();
  const record=await page.request.post(base+'/api/cases',{headers:{Origin:base},data:{title:'로그인으로 이어지는 문의',messages:[{role:'customer',text:'언제 답변이 오나요?'}]}});assert.equal(record.status(),201);
  await page.locator('[data-action=account]').click();await page.locator('[data-action=join]').click();
  await page.locator('#confirm-field').waitFor();await page.locator('#auth-switch').click();
  await page.locator('[name=username]').fill('guest_browser');await page.locator('[name=password]').fill('Guest-browser-1234');await page.locator('#auth-submit').click();await page.locator('.account-button').waitFor();
  assert.equal((await (await page.request.get(base+'/api/cases')).json()).length,2);
  await other.locator('[data-action=account]').click();other.once('dialog',d=>d.accept());await other.locator('[data-action=logout]').click();await other.locator('#guest-start').waitFor();
  assert.deepEqual(errors,[]);
  await writeFile(`${dir}/result.json`,JSON.stringify({passed:true,viewports:[1440,390],anonymousFlow:true,isolated:true,signupPreserves:true,loginMerges:true,ai:'fixtures, no live calls',errors},null,2));
  console.log('Guest browser flow passed: entry, analysis, English draft, reply comparison, reload, isolation, signup, login merge, logout and mobile.');
}finally{await browser.close();await new Promise(r=>app.server.close(r));await database.close();}
